"""Routing rules for the placed boards: net classes in each project (.kicad_pro) and custom DRC rules (.kicad_dru), from
routing_guide.md and emc_placement_study.md. Settings only, no copper. Run with KiCad's Python after any re-placement
or netlist change (the classes are assigned by exact net name, and unnamed nets are named by their pins):
  $KPY tools/netrules.py [board ...]          (default: the strip, group, master and jig boards with their jack boards)
Classes, first match wins:
  Ground       GNDA, GNDD, GNDM, PHONESGND (pours; tracks where a pour can't reach)
  Chassis      CHASSIS (jack sleeves and the plated standoffs)
  Power        the bus and op-amp rails (+-VBUS*, +-VA, +-VP, +-VM)
  LogicSupply  +-VL, +5VL
  Bus          signal lines on the 34-way bus header (summing buses, PFL, PFLDET, GCANCEL)
  Entry        signal lines on a jack or a board-to-board link (they arrive from outside the board)
  HighZ        op-amp input nets with no op-amp output on them (summing nodes, resistor-fed + inputs, pot wipers)
  Switching    LED, comparator-output, DG413-logic, relay-coil and transistor nets (tools/emc_check.py aggressors)
  Default      everything else (op-amp outputs and the low-impedance audio between stages)
The rules keep HighZ / Entry / Bus copper 1 mm from Switching and 0.5 mm from LogicSupply (tracks, vias and zones;
pad to pad is placement, which tools/emc_check.py measures: a DG413's logic pin sits 0.67 mm from a bus pin), GNDD 0.5 mm from GNDA (the two
grounds meet only at the net tie), CHASSIS 0.5 mm from everything else, Power and Ground tracks wide, and flag a HighZ
net routed longer than 60 mm. On the 4-layer boards (the strip, group and master mains) they also keep In1.Cu (GND) free
of tracks and of anything but ground zones, and HighZ / Entry / Bus tracks off In2.Cu (PWR)."""
import json, os, re, sys
import pcbnew
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from emc_check import load, classify

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
BOARDS = ('channel_strip', 'jack_board', 'group', 'group_jack_board', 'master', 'master_jack_board',
          'jig_master_stub', 'jig_load_board')
GROUND = {'GNDA', 'GNDD', 'GNDM', 'PHONESGND'}
POWER = re.compile(r'^[+-](VBUS(_[LR])?|VA|VP|VM)$')
LOGIC = {'+VL', '-VL', '+5VL'}
OPAMP = ('OPA', 'DRV13')
# name: (track width, clearance, via diameter, via drill), mm
CLASSES = {'Default': (0.25, 0.2, 0.6, 0.3), 'Ground': (0.6, 0.2, 0.6, 0.3), 'Chassis': (1.5, 0.5, 0.8, 0.4),
           'Power': (0.8, 0.2, 0.8, 0.4), 'LogicSupply': (0.4, 0.2, 0.6, 0.3), 'Bus': (0.3, 0.2, 0.6, 0.3),
           'Entry': (0.3, 0.2, 0.6, 0.3), 'HighZ': (0.2, 0.2, 0.6, 0.3), 'Switching': (0.25, 0.2, 0.6, 0.3)}
# class clearances stay at the board's 0.2 mm: footprints have pad gaps down to 0.25 mm (the load board's slide switches);
# the wider spacings are track rules in DRU
DRU = """(version 1)
# GENERATED by tools/netrules.py (routing_guide.md); edit the script, not this file
# KiCad: where several rules set the same constraint, the later one in this file wins, so the general
# track spacing comes first and the wider, more specific spacings after it
(rule "bus, entry and high-impedance tracks 0.3 mm from other copper"
  (condition "(A.NetClass == 'Bus' || A.NetClass == 'Entry' || A.NetClass == 'HighZ') && A.Type == 'Track' && A.NetName != B.NetName")
  (constraint clearance (min 0.3mm)))
(rule "sensitive lines 0.5 mm from logic supplies"
  (condition "(A.NetClass == 'HighZ' || A.NetClass == 'Entry' || A.NetClass == 'Bus') && B.NetClass == 'LogicSupply' && (A.Type != 'Pad' || B.Type != 'Pad')")
  (constraint clearance (min 0.5mm)))
(rule "sensitive lines 1 mm from switching lines"
  (condition "(A.NetClass == 'HighZ' || A.NetClass == 'Entry' || A.NetClass == 'Bus') && B.NetClass == 'Switching' && (A.Type != 'Pad' || B.Type != 'Pad')")
  (constraint clearance (min 1.0mm)))
(rule "GNDD 0.5 mm from GNDA (they meet only at the net tie)"
  (condition "A.NetName == 'GNDD' && B.NetName == 'GNDA'")
  (constraint clearance (min 0.5mm)))
(rule "CHASSIS 0.5 mm from everything else"
  (condition "A.NetClass == 'Chassis' && B.NetClass != 'Chassis'")
  (constraint clearance (min 0.5mm)))
(rule "high-impedance nets short"
  (condition "A.NetClass == 'HighZ'")
  (constraint length (max 60mm)))
(rule "power tracks wide"
  (condition "A.NetClass == 'Power' && A.Type == 'Track'")
  (constraint track_width (min 0.5mm) (opt 0.8mm)))
(rule "ground tracks wide"
  (condition "A.NetClass == 'Ground' && A.Type == 'Track'")
  (constraint track_width (min 0.4mm) (opt 0.6mm)))
"""

DRU4 = """# 4-layer boards (layer_study.md): In1.Cu = GND, a solid GNDA plane; In2.Cu = PWR, the supply rails as pours or wide
# tracks and the GNDD spine beside +VL / +5VL to the net tie
(rule "GND plane: no tracks"
  (layer "In1.Cu")
  (constraint disallow track))
(rule "GND plane: ground zones only"
  (layer "In1.Cu")
  (condition "A.Type == 'Zone' && A.NetClass != 'Ground'")
  (constraint disallow zone))
(rule "sensitive nets off the power layer"
  (layer "In2.Cu")
  (condition "A.NetClass == 'HighZ' || A.NetClass == 'Entry' || A.NetClass == 'Bus'")
  (constraint disallow track))
"""

def classes_of(path):
    parts, nets = load(path)                          # names without the hierarchical '/'
    vict, agg, entry = classify(parts)
    b = pcbnew.LoadBoard(path)
    real = {p.GetNetname().lstrip('/'): p.GetNetname() for f in b.GetFootprints() for p in f.Pads() if p.GetNetname()}
    bus = {n for r, c in parts.items() if r.startswith('CN') and 'x17' in c['fp'] for _, n, _ in c['pads']}
    out = {}
    for n, ps in nets.items():
        if n.startswith('unconnected'): continue
        ins = [p for r, p, xy, s in ps if r.startswith('U') and parts[r]['value'].startswith(OPAMP) and p in ('2', '3', '5', '6')]
        outs = [p for r, p, xy, s in ps if r.startswith('U') and parts[r]['value'].startswith(OPAMP) and p in ('1', '7')]
        if n in GROUND: c = 'Ground'
        elif n == 'CHASSIS': c = 'Chassis'
        elif POWER.match(n): c = 'Power'
        elif n in LOGIC: c = 'LogicSupply'
        elif n in bus: c = 'Bus'
        elif n in entry: c = 'Entry'
        elif ins and not outs and len(ins) < 3: c = 'HighZ'
        elif n in agg: c = 'Switching'
        else: c = 'Default'
        out[real.get(n, n)] = c
    return out

def write(name):
    pcb, pro = os.path.join(ROOT, name + '.kicad_pcb'), os.path.join(ROOT, name + '.kicad_pro')
    cls = classes_of(pcb)
    d = json.load(open(pro))
    if 'net_settings' not in d:                       # a project KiCad never saved with net settings: start from the strip's
        d['net_settings'] = json.load(open(os.path.join(ROOT, 'channel_strip.kicad_pro')))['net_settings']
    ns = d['net_settings']
    base = next(c for c in ns['classes'] if c['name'] == 'Default')
    new = []
    for i, (cn, (w, cl, vd, vdr)) in enumerate(CLASSES.items()):
        c = dict(base); c.update(name=cn, track_width=w, clearance=cl, via_diameter=vd, via_drill=vdr)
        if cn != 'Default': c['priority'] = i
        new.append(c)
    ns['classes'] = new
    ns['netclass_patterns'] = [{'netclass': c, 'pattern': n} for n, c in sorted(cls.items()) if c != 'Default']
    ns['netclass_assignments'] = {}
    with open(pro, 'w') as f: json.dump(d, f, indent=2); f.write('\n')
    four = pcbnew.LoadBoard(pcb).GetCopperLayerCount() == 4
    with open(os.path.join(ROOT, name + '.kicad_dru'), 'w') as f: f.write(DRU + (DRU4 if four else ''))
    count = {}
    for c in cls.values(): count[c] = count.get(c, 0) + 1
    print(f'{name}: ' + ', '.join(f'{k} {count.get(k, 0)}' for k in CLASSES))

if __name__ == '__main__':
    for n in sys.argv[1:] or BOARDS: write(n)
